"""PII 脱敏：在文本进入模型前遮蔽个人敏感信息。

医学场景中病历文本常含身份证号、手机号、姓名、住址等个人信息。
脱敏的目的：
1. 合规：降低个人信息泄露风险（《个人信息保护法》等要求）；
2. 安全：防止敏感信息进入模型上下文后被不当输出。

注意：本模块为演示级规则实现（正则匹配），
生产环境应配合命名实体识别模型与严格的审计流程。
"""
from __future__ import annotations

import re

# 常见姓氏（用于"姓名"上下文的保守匹配，避免误伤普通词）
_SURNAMES = "赵钱孙李周吴郑王冯陈褚卫蒋沈韩杨朱秦尤许何吕施张孔曹严华金魏陶姜谢邹喻柏水窦章苏潘葛奚范彭郎鲁韦昌马苗凤花方俞任袁柳酆鲍史唐费廉岑薛雷贺倪汤滕殷罗毕郝邬安常乐于时傅皮卞齐康伍余元卜顾孟平黄和穆萧尹姚邵湛汪祁毛禹狄米贝明臧计伏成戴谈宋茅庞熊纪舒屈项祝董梁杜阮蓝闵席季麻强贾路娄危江童颜郭梅盛林刁钟徐邱骆高夏蔡田樊胡凌霍虞万支柯昝管卢莫经房裘缪干解应宗丁宣贲邓郁单杭洪包诸左石崔吉钮龚程嵇邢滑裴陆荣翁荀羊於惠甄曲家封芮羿储靳汲邴糜松井段富巫乌焦巴弓牧隗山谷车侯宓蓬全郗班仰秋仲伊宫宁仇栾暴甘钭厉戎祖武符刘景詹束龙叶幸司韶郜黎蓟薄印宿白怀蒲邰从鄂索咸籍赖卓蔺屠蒙池乔阴郁胥能苍双闻莘党翟谭贡劳逄姬申扶堵冉宰郦雍却璩桑桂濮牛寿通边扈燕冀郏浦尚农温别庄晏柴瞿阎充慕连茹习宦艾鱼容向古易慎戈廖庾终暨居衡步都耿满弘匡国文寇广禄阙东欧殳沃利蔚越夔隆师巩厍聂晁勾敖融冷訾辛阚那简饶空曾毋沙乜养鞠须丰巢关蒯相查后荆红游竺权逯盖益桓公"

_PATTERNS = [
    # 身份证号：18 位（末位可为 X）——必须先于手机号匹配，
    # 否则手机号规则会抢先吃掉身份证号中间的数字段
    (re.compile(r"(?<!\d)\d{17}[\dXx](?!\d)"), "<身份证号>"),
    # 手机号：1 开头 11 位（带数字边界，避免误伤长数字串）
    (re.compile(r"(?<!\d)1[3-9]\d{9}(?!\d)"), "<手机号>"),
    # 住院号/病历号等编号
    (re.compile(r"(住院号|病历号|门诊号|登记号|ID)[:：\s]*[A-Za-z0-9_-]+"), r"\1<编号>"),
    # 姓名（常见上下文：患者/姓名/联系人 后跟 2-4 个汉字）
    (re.compile(r"(患者|姓名|联系人|本人)[:：\s]*([%s]{1,2}(?:[%s][\u4e00-\u9fff])?[\u4e00-\u9fff]{0,1})" % (_SURNAMES, _SURNAMES)),
     lambda m: f"{m.group(1)}<姓名>"),
    # 姓氏 + 某（如"张某""李某"）
    (re.compile(rf"[{_SURNAMES}]某"), "<姓名>"),
    # 住址（省市区县 + 道路村街 + 门牌号）
    (re.compile(r"[\u4e00-\u9fff]{2,6}(?:省|自治区|市|县|区)[\u4e00-\u9fff]{2,12}(?:路|街|道|巷|镇|村)\d{0,6}号?"), "<地址>"),
    # 银行卡号：16-19 位数字
    (re.compile(r"(?<!\d)\d{16,19}(?!\d)"), "<银行卡号>"),
]


def desensitize(text: str) -> str:
    """对文本中的 PII 做遮蔽处理，返回脱敏后的文本。"""
    out = text
    for pattern, repl in _PATTERNS:
        out = pattern.sub(repl, out)
    return out


def contains_pii(text: str) -> bool:
    """判断文本是否仍包含明显的 PII（脱敏前后对比）。"""
    return desensitize(text) != text
